export const getDailyHealthTip = (date = new Date()) => {
  const dayNumber = Math.floor(Date.UTC(date.getFullYear(), date.getMonth(), date.getDate()) / 86_400_000);
  return dailyHealthTips[dayNumber % dailyHealthTips.length];
};
